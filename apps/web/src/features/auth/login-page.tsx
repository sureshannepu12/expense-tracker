import { zodResolver } from '@hookform/resolvers/zod'
import { Sparkles } from 'lucide-react'
import { useForm } from 'react-hook-form'
import { Link, useLocation, useNavigate } from 'react-router'
import { toast } from 'sonner'
import { z } from 'zod'
import { useLogin } from '@/api/generated/auth/auth'
import { FormInput } from '@/components/form-input'
import { Button } from '@/components/ui/button'
import { FieldGroup } from '@/components/ui/field'
import { useAuthStore } from '@/lib/auth-store'
import { getErrorMessage } from '@/lib/errors'
import { AuthLayout } from './auth-layout'

const loginSchema = z.object({
  email: z.email('Enter a valid email'),
  password: z.string().min(1, 'Password is required'),
})
type LoginValues = z.infer<typeof loginSchema>

export function LoginPage() {
  const navigate = useNavigate()
  const location = useLocation()
  const setSession = useAuthStore((s) => s.setSession)
  const {
    register,
    handleSubmit,
    setValue,
    formState: { errors },
  } = useForm<LoginValues>({
    resolver: zodResolver(loginSchema),
    defaultValues: { email: '', password: '' },
  })

  // useLogin is generated by Orval from POST /auth/login.
  const login = useLogin({
    mutation: {
      onSuccess: ({ accessToken, user }) => {
        setSession(accessToken, user)
        toast.success(`Welcome back, ${user.name}!`)
        const from = (location.state as { from?: string } | null)?.from
        navigate(from ?? '/', { replace: true })
      },
      onError: (error) => toast.error(getErrorMessage(error)),
    },
  })

  const fillDemo = () => {
    setValue('email', 'demo@example.com')
    setValue('password', 'password123')
  }

  return (
    <AuthLayout
      title="Welcome back"
      description="Log in to see your spending."
      footer={
        <span>
          No account?{' '}
          <Link to="/register" className="font-medium text-primary underline-offset-4 hover:underline">
            Create one
          </Link>
        </span>
      }
    >
      <div className="mb-6 flex flex-wrap items-center gap-3 rounded-lg border border-primary/20 bg-accent p-3 text-sm text-accent-foreground">
        <Sparkles className="size-4 shrink-0" />
        <div className="min-w-40 flex-1">
          <p className="font-medium">Just looking around?</p>
          <p className="text-xs opacity-80">demo@example.com · password123</p>
        </div>
        <Button type="button" size="sm" variant="outline" onClick={fillDemo}>
          Use demo account
        </Button>
      </div>

      <form onSubmit={handleSubmit((data) => login.mutate({ data }))}>
        <FieldGroup>
          <FormInput
            id="email"
            label="Email"
            type="email"
            autoComplete="email"
            error={errors.email}
            {...register('email')}
          />
          <FormInput
            id="password"
            label="Password"
            type="password"
            autoComplete="current-password"
            error={errors.password}
            {...register('password')}
          />
          <Button type="submit" size="lg" disabled={login.isPending}>
            {login.isPending ? 'Logging in…' : 'Log in'}
          </Button>
        </FieldGroup>
      </form>
    </AuthLayout>
  )
}
